// RenderCSV returns the same scores as Render, as CSV (header + one row per pair).
func RenderCSV() string {
	cols, rows := compute()
	var buf bytes.Buffer
	w := csv.NewWriter(&buf)
	header := []string{"query", "index", "note"}
	for _, c := range cols {
		header = append(header, c.hdr)
	}
	_ = w.Write(header)
	for _, row := range rows {
		rec := []string{row.query, row.index, row.note}
		for _, s := range row.scores {
			rec = append(rec, fmt.Sprintf("%.3f", s))
		}
		_ = w.Write(rec)
	}
	w.Flush()
	return buf.String()
}

func score(q, idx []string, cfg stringscore.ScoringConfig, tf *tfidf.Index) float64 {
	if tf != nil && tf.Enabled() {
		qw := tf.GetWeights(q)
		iw := tf.GetWeights(idx)
		return stringscore.BestPairCombinationJaroWinklerWeightedWithConfig(q, idx, qw, iw, cfg)
	}
	return stringscore.BestPairCombinationJaroWinklerWithConfig(q, idx, cfg)
}

func buildIndex() *tfidf.Index {
	cfg := tfidf.DefaultConfig()
	cfg.Enabled = true
	idx := tfidf.NewIndex(cfg)
	var docs [][]string
	seen := map[string]bool{}
	for _, p := range pairs {
		for _, name := range []string{p.query, p.index} {
			if seen[name] {
				continue
			}
			seen[name] = true
			docs = append(docs, strings.Fields(name))
		}
	}
	idx.Build(docs)
	return idx
}
