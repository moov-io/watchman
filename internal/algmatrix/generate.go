type pair struct {
	query, index, note string
}

var pairs = []pair{
	{"precede", "preceed", "spelling / doubled letter"}, //nolint:misspell
	{"achieve", "acheive", "transposition"},             //nolint:misspell
	{"smith", "smythe", "phonetic (English)"},
	{"catherine", "katherine", "C/K onset"},
	{"qaddafi", "gaddafi", "Q/G onset"},
	{"aleksandr", "alexander", "transliteration"},
	{"nicolas maduro", "nicolas moros maduro", "missing middle"},
	{"alexander lukashenko", "lukashenko alexander grigoryevich", "token order / extra given"},
	{"saddam hussein", "saddam hussein al tikriti", "missing suffix"},
	{"hadi", "hadi alwai", "short vs longer"},
	{"li shangfu", "li shanlan", "shared short token"},
	{"vladimir", "vladimirov vladimir vladimirovich", "doubled family"},
	{"dominguez", "jimenez", "false-positive control"},
	{"cycloserine", "cyclosporine", "LASA look-alike"},
	{"schumacher", "shumaker", "German / English spelling"},
}

type column struct {
	key   string
	hdr   string
	cfg   stringscore.ScoringConfig
	tfidf bool
}

func columns() []column {
	jw := stringscore.ScoringConfig{}
	return []column{
		{key: "jw", hdr: "jw", cfg: jw},
		{key: "jw-tfidf", hdr: "jw+tfidf", cfg: jw, tfidf: true},
		{key: "soundex", hdr: "soundex", cfg: stringscore.ScoringConfig{UseSoundexBoost: true, SoundexBoostWeight: 0.12}},
		{key: "dmeta", hdr: "dmeta", cfg: stringscore.ScoringConfig{UseDoubleMetaphoneBoost: true, SoundexBoostWeight: 0.12}},
		{key: "bmpm", hdr: "bmpm", cfg: stringscore.ScoringConfig{UseBeiderMorseBoost: true, SoundexBoostWeight: 0.12}},
		{key: "bidist", hdr: "bidist", cfg: stringscore.ScoringConfig{TokenScorer: stringscore.TokenScorerSoftBidist}},
		{key: "bidist-tfidf", hdr: "bidist+tfidf", cfg: stringscore.ScoringConfig{TokenScorer: stringscore.TokenScorerSoftBidist}, tfidf: true},
		{key: "bisim", hdr: "bisim", cfg: stringscore.ScoringConfig{TokenScorer: stringscore.TokenScorerSoftBisim}},
		{key: "editex", hdr: "editex", cfg: stringscore.ScoringConfig{TokenScorer: stringscore.TokenScorerEditex}},
		{key: "editex-tfidf", hdr: "editex+tfidf", cfg: stringscore.ScoringConfig{TokenScorer: stringscore.TokenScorerEditex}, tfidf: true},
		{key: "nsim", hdr: "nsim", cfg: stringscore.ScoringConfig{TokenScorer: stringscore.TokenScorerNSim}},
		{key: "nsim3", hdr: "nsim-3", cfg: stringscore.ScoringConfig{TokenScorer: stringscore.TokenScorerNSim3}},
	}
}

type scoredRow struct {
	pair
	scores []float64
}

func compute() ([]column, []scoredRow) {
	idx := buildIndex()
	cols := columns()
	rows := make([]scoredRow, 0, len(pairs))
	for _, p := range pairs {
		q := strings.Fields(p.query)
		ix := strings.Fields(p.index)
		scores := make([]float64, len(cols))
		for i, c := range cols {
			var tf *tfidf.Index
			if c.tfidf {
				tf = idx
			}
			scores[i] = score(q, ix, c.cfg, tf)
		}
		rows = append(rows, scoredRow{pair: p, scores: scores})
	}
	return cols, rows
}

